# ---------------- 加载源文件 ----------------
ZJ = 'zhejiang-talent-data.json'
zj = json.load(open(ZJ, encoding='utf-8'))

gd = {}   # city -> (path, data)
for f in sorted(glob.glob('guangdong_raw/*.json')):
    dd = json.load(open(f, encoding='utf-8'))
    cname = dd.get('city', '').replace('市', '')
    gd[cname] = (f, dd)

def locate(city):
    """返回 (container, city_key)"""
    if city in zj:
        return zj, city
    if city in gd:
        return gd[city][1], None
    raise KeyError(city)

# ---------------- 应用 ----------------
changed = []
errors = []
for city, rules in M.items():
    cont, ckey = locate(city)
    node = cont[city] if ckey else cont
    items = node['dimensions']['grad_subsidy']['items']
    for (idx, old_cash, new_cash, new_hv, note_add) in rules:
        if idx >= len(items):
            errors.append(f'{city}[{idx}] 索引越界（共{len(items)}条）')
            continue
        it = items[idx]
        cur = str(it.get('cash', '') or '')
        if cur != old_cash:
            errors.append(f'{city}[{idx}] 原文不符\n  期望: {old_cash[:80]}\n  实际: {cur[:80]}')
            continue
        it['cash'] = new_cash
        if new_hv is not None:
            it['house_voucher'] = new_hv
        if note_add:
            it['note'] = (str(it.get('note', '') or '') + note_add).strip()
        changed.append(f'{city}[{idx}]')

if errors:
    print('❌ 校验失败，未写入任何文件：')
    for e in errors:
        print('  ' + e)
    sys.exit(1)

