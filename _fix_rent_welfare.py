# ============ 执行 ============
errors, done = [], []
for city, w in WELFARE_ADD.items():
    nd = node(city)
    items = nd['dimensions']['welfare']['items']
    # 幂等：已存在同 type 条目则跳过
    if any(it.get('type') == w['type'] for it in items):
        done.append(f'{city} welfare[{w["type"]}] 已存在跳过')
        continue
    items.append(w)
    done.append(f'{city} welfare += {w["type"]}')

for city, idx, old, new, note_add in GRAD_FIX:
    nd = node(city)
    it = nd['dimensions']['grad_subsidy']['items'][idx]
    cur = str(it.get('cash', '') or '')
    if cur != old:
        errors.append(f'{city} grad[{idx}] 原文不符\n  期望: {old[:70]}\n  实际: {cur[:70]}')
        continue
    it['cash'] = new
    if note_add:
        it['note'] = (str(it.get('note', '') or '') + '。' + note_add).strip('。')
    done.append(f'{city} grad[{idx}] cash 剥离')

# 丽水 source 修正
for idx in range(4):
    it = node('丽水')['dimensions']['grad_subsidy']['items'][idx]
    if '丽政办发' in str(it.get('source', {}).get('doc_no', '')):
        it['source'] = dict(LS_SRC)
        it['note'] = LS_NOTE + ' ' + str(it.get('note', '') or '')
        done.append(f'丽水 grad[{idx}] source 已换')

if errors:
    print('❌ 校验失败，未写入：')
    for e in errors:
        print(' ', e)
    sys.exit(1)

json.dump(zj, open(ZJ, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
for cname, (f, dd) in gd.items():
    json.dump(dd, open(f, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)

print(f'✅ 完成 {len(done)} 项：')
for d in done:
    print('  ', d)
